export const platformColor: Record<Platform, string> = {
  Facebook: "#0866FF",
  TikTok: "#000000",
  Telegram: "#26A5E4",
  Instagram: "#E4405F",
  LinkedIn: "#0A66C2",
};

export function SocialGlyph({ platform, className }: { platform: Platform; className?: string }) {
  return (
    <svg viewBox="0 0 24 24" className={className} aria-hidden="true" focusable="false">
      {platform === "TikTok" ? (
        <>
          {/* TikTok's signature cyan / red offset */}
          <path d={paths.TikTok} fill="#25F4EE" transform="translate(-0.7 -0.5)" />
          <path d={paths.TikTok} fill="#FE2C55" transform="translate(0.7 0.5)" />
          <path d={paths.TikTok} fill="#ffffff" />
        </>
      ) : (
        <path d={paths[platform]} fill="currentColor" />
      )}
    </svg>
  );
}

/** Brand-coloured badge with the platform mark. */
export function SocialBadge({ platform, className, size = "md" }: { platform: Platform; className?: string; size?: "sm" | "md" | "lg" }) {
  const dims = size === "sm" ? "h-8 w-8" : size === "lg" ? "h-12 w-12" : "h-10 w-10";
  const glyph = size === "sm" ? "h-4 w-4" : size === "lg" ? "h-6 w-6" : "h-5 w-5";
  return (
    <span
      className={cn("grid shrink-0 place-items-center rounded-full text-white shadow-[0_6px_20px_-8px_rgba(0,0,0,0.6)]", dims, className)}
      style={{ background: platformColor[platform] }}
      aria-hidden="true"
    >
      <SocialGlyph platform={platform} className={glyph} />
    </span>
  );
}

export function isPlatform(label: string): label is Platform {
  return label in paths;
}
